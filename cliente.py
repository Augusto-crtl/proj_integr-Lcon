import requests, json, time, random

SERVER = "http://localhost/api"
DEVICE_ID = "ESP32_SIM_01"
TOKEN = "seu_token_aqui"

while True:
    # Simula leitura de sensores e envia ao servidor
    data = {
        "device_id": DEVICE_ID,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "variables": {
            "temp": round(22 + random.random() * 4, 2),
            "nivel": round(50 + random.random() * 10, 2)
        }
    }
    headers = {"Authorization": f"Bearer {TOKEN}"}
    r = requests.post(f"{SERVER}/readings", json=data, headers=headers)
    print("[POST]", r.status_code, r.text)

    # Consulta comandos pendentes
    c = requests.get(f"{SERVER}/commands", headers=headers)
    if c.status_code == 200 and c.text.strip() != "":
        try:
            cmds = c.json()
            for cmd in cmds:
                print(f"[CMD RECEBIDO] {cmd['name']} -> {cmd['value']}")
            # Confirma execução
            requests.post(f"{SERVER}/commands/ack", json={"device_id": DEVICE_ID}, headers=headers)
        except:
            pass

    time.sleep(5)