import requests, json, time, random

SERVER = "http://localhost/api/readings"
DEVICE_ID = "ESP32_SIMULADO_01"
TOKEN = "seu_token_aqui"

while True:
    payload = {
        "device_id": DEVICE_ID,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "variables": {
            "temp": round(20 + 5 * random.random(), 2),
            "nivel": round(60 + 10 * random.random(), 2)
        }
    }
    headers = {"Authorization": f"Bearer {TOKEN}"}
    r = requests.post(SERVER, data=json.dumps(payload), headers=headers)
    print("Status:", r.status_code, "Resposta:", r.text)
    time.sleep(5)
